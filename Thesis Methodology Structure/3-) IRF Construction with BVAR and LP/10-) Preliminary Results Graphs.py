# SECTION 3 — FILE HELPER FUNCTIONS
# ============================================================

def find_first(pattern: str) -> str:
    """
    Find the first file in IRF_DIR whose name fully matches a regex pattern.

    Using regex matching rather than exact filenames makes the script
    robust to changes in the p (lag order) and H (horizon) values baked
    into the CSV filenames by bvar_irf_estimation.py. The first
    alphabetically sorted match is returned.

    Parameters
    ----------
    pattern : str  Regex pattern to match against filenames in IRF_DIR.
                   Must be a full-match pattern (anchored at both ends).

    Returns
    -------
    str  Absolute path to the matched file.

    Raises
    ------
    FileNotFoundError  If no file in IRF_DIR matches the pattern.
    """
    rx = re.compile(pattern)
    for fn in sorted(os.listdir(IRF_DIR)):
        if rx.fullmatch(fn):
            return os.path.join(IRF_DIR, fn)
    raise FileNotFoundError(
        f"Could not find a file matching:\n  {pattern}\nIn:\n  {IRF_DIR}"
    )


def read_irf_csv(path: str):
    """
    Read a saved IRF CSV table and return arrays ready for plotting.

    The CSV format produced by bvar_irf_estimation.py has columns:
        h                — horizon index (0, 1, ..., H)
        {var}_med        — posterior median IRF
        {var}_lo         — lower credible band (16th percentile)
        {var}_hi         — upper credible band (84th percentile)

    Variables are returned in the order they appear in the CSV,
    which matches the macro_vars ordering in bvar_irf_estimation.py.

    Parameters
    ----------
    path : str  Absolute path to the IRF CSV file.

    Returns
    -------
    h       : np.ndarray   Horizon array (H+1,).
    ordered : list of str  Variable names in CSV column order.
    med     : dict         {var: np.ndarray} posterior medians.
    lo      : dict         {var: np.ndarray} lower credible bands.
    hi      : dict         {var: np.ndarray} upper credible bands.

    Raises
    ------
    ValueError  If the 'h' column or any required _med/_lo/_hi column
                is missing from the CSV.
    """
    df = pd.read_csv(path)
    if "h" not in df.columns:
        raise ValueError(
            f"'h' column missing in {path}. Columns: {list(df.columns)}"
        )

    h = df["h"].to_numpy()

    # Identify variables from columns ending with _med
    vars_found = []
    for c in df.columns:
        if c.endswith("_med"):
            vars_found.append(c[:-4])
    vars_found = sorted(set(vars_found))

    # Apply PREFERRED_ORDER; append any extra variables not in the list
    ordered = [v for v in PREFERRED_ORDER if v in vars_found] + \
              [v for v in vars_found if v not in PREFERRED_ORDER]

    med, lo, hi = {}, {}, {}
    for v in ordered:
        for suf in ["_med", "_lo", "_hi"]:
            col = v + suf
            if col not in df.columns:
                raise ValueError(f"Missing column '{col}' in {path}.")
        med[v] = df[v + "_med"].to_numpy()
        lo[v]  = df[v + "_lo"].to_numpy()
        hi[v]  = df[v + "_hi"].to_numpy()

    return h, ordered, med, lo, hi


