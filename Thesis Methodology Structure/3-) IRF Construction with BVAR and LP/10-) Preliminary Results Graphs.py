# SECTION 5 — MAIN EXECUTION
# ============================================================

def main():
    """
    Main execution function: locate CSVs, read IRFs, and produce figures.

    Execution order:
        1. Locate the three required IRF CSV files by regex pattern
        2. Read each CSV into horizon arrays and IRF dictionaries
        3. Compute variable intersections for overlay figures
        4. Warn if horizon arrays differ between series
        5. Produce Figure 1: Pre-2008 AD vs FFR
        6. Produce Figure 2: Post-2008 Wu-Xia only
        7. Produce Figure 3: Cross-regime FFR vs Wu-Xia
        8. Print a summary of input and output file locations

    The Hybrid CSV is read and labelled as "FFR" in all plots because
    the Hybrid series is the FFR-based shock — the label "Hybrid" is
    an internal construction label, not the thesis-facing name.
    """

    # ── Step 1: Locate required IRF CSV files ────────────────────────────────
    # Regex patterns match regardless of exact p and H values in the filename
    ad_pre_path  = find_first(r"Table_IRF_AruobaDrechsel_Pre2008_p\d+_H\d+_EBP\.csv")
    hy_pre_path  = find_first(r"Table_IRF_Hybrid_Pre2008_p\d+_H\d+_EBP\.csv")
    wx_post_path = find_first(r"Table_IRF_WuXia_Post2008_p\d+_H\d+_EBP\.csv")

    # ── Step 2: Read IRF CSV files ────────────────────────────────────────────
    h_ad,  vars_ad,  med_ad,  lo_ad,  hi_ad  = read_irf_csv(ad_pre_path)
    # Hybrid series read here — displayed as "FFR" in all figures
    h_ffr, vars_ffr, med_ffr, lo_ffr, hi_ffr = read_irf_csv(hy_pre_path)
    h_wx,  vars_wx,  med_wx,  lo_wx,  hi_wx  = read_irf_csv(wx_post_path)

    # ── Step 3: Variable intersections for overlay figures ────────────────────
    # Variables present in both series, in PREFERRED_ORDER
    common_vars_pre = [v for v in PREFERRED_ORDER if (v in vars_ad and v in vars_ffr)]

    common_vars_ffr_wx = [v for v in PREFERRED_ORDER if (v in vars_ffr and v in vars_wx)]

    # ── Step 4: Horizon alignment warnings ────────────────────────────────────
    if len(h_ad) != len(h_ffr) or not np.allclose(h_ad, h_ffr):
        print("PRE horizons differ between AD and FFR; using AD horizon for Figure 1.")
    if len(h_ffr) != len(h_wx) or not np.allclose(h_ffr, h_wx):
        print("Horizons differ between PRE FFR and POST Wu-Xia; using PRE horizon for Figure 3.")

    # ── Figure 1: Pre-2008 AD vs FFR (Hybrid labeled as FFR) ─────────────────
    out1 = os.path.join(OUTDIR, "Figure_Pre2008_Compare_AD_vs_FFR.png")
    plot_overlay_two_shocks(
        h_ad,
        common_vars_pre,
        (med_ad,  lo_ad,  hi_ad),
        (med_ffr, lo_ffr, hi_ffr),
        labelA = "AD",
        labelB = "FFR",
        title  = "Pre-2008: IRFs to AD vs FFR Monetary Policy Shocks",
        out_png = out1,
    )

    # ── Figure 2: Post-2008 Wu-Xia only ──────────────────────────────────────
    out2 = os.path.join(OUTDIR, "Figure_Post2008_IRF_WuXia.png")
    # Variables in PREFERRED_ORDER that are present in the Wu-Xia CSV
    vars_wx_plot = [v for v in PREFERRED_ORDER if v in vars_wx] + \
                   [v for v in vars_wx if v not in PREFERRED_ORDER]
    plot_single_shock(
        h_wx,
        vars_wx_plot,
        med_wx, lo_wx, hi_wx,
        title   = "Post-2008: IRFs to Wu-Xia Monetary Policy Shock",
        out_png = out2,
    )

    # ── Figure 3: Cross-regime PRE FFR vs POST Wu-Xia ────────────────────────
    # PRE horizon used by default (consistent with thesis wording)
    out3 = os.path.join(OUTDIR, "Figure_CrossRegime_Compare_PreFFR_vs_PostWuXia.png")
    plot_overlay_two_shocks(
        h_ffr,
        common_vars_ffr_wx,
        (med_ffr, lo_ffr, hi_ffr),
        (med_wx,  lo_wx,  hi_wx),
        labelA  = "FFR (Pre-2008)",
        labelB  = "Wu-Xia (Post-2008)",
        title   = "Cross-regime: Pre-2008 FFR vs Post-2008 Wu-Xia",
        out_png = out3,
    )

    # ── Summary ───────────────────────────────────────────────────────────────
    print("\nDone.")
    print("Inputs:")
    print("  AD PRE  :", ad_pre_path)
    print("  FFR PRE :", hy_pre_path, " (Hybrid series labeled as FFR)")
    print("  WX POST :", wx_post_path)
    print("Outputs saved to:")
    print(" ", OUTDIR)


if __name__ == "__main__":
    main()