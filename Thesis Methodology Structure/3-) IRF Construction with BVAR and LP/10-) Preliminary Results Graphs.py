import os
import re
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt


# ============================================================
# SECTION 1 — PATH CONFIGURATION
# ============================================================
# All paths are resolved relative to the current working directory.
# IRF CSV tables are read from irf_outputs_EBP_final/ (produced by
# bvar_irf_estimation.py). Thesis figures are saved to a dedicated
# subfolder to keep them separate from the estimation outputs.

BASE_DIR = os.getcwd()

# Folder containing the IRF CSV tables from bvar_irf_estimation.py
IRF_DIR = os.path.join(BASE_DIR, "irf_outputs_EBP_final")

# Output folder for thesis-ready figures
OUTDIR  = os.path.join(IRF_DIR, "thesis_figures_from_csv")
os.makedirs(OUTDIR, exist_ok=True)


# ============================================================
# SECTION 2 — DISPLAY SETTINGS
# ============================================================
# Y-axis labels match the units used in the BVAR estimation.
# DISPLAY_LABELS maps internal column names to thesis-ready axis labels.
# Variables appear in the figures in the order they are stored in the IRF
# CSV files, which matches the macro_vars order in bvar_irf_estimation.py.

DISPLAY_LABELS = {
    "y1":        "1Y Gov Bond (%)",
    "log_sp500": "S&P500 (100 × log)",
    "log_rgdp":  "Real GDP (100 × log)",
    "unemp":     "Unemployment (%)",
    "log_pgdp":  "GDP Deflator (100 × log)",
    "EBP":       "EBP (%)",
}



# Fixed variable order for all thesis figures — matches macro_vars
# in bvar_irf_estimation.py exactly.
PREFERRED_ORDER = ["y1", "log_sp500", "log_rgdp", "unemp", "log_pgdp", "EBP"]


def pretty_ylabel(varname: str) -> str:
    """Return the thesis-standard y-axis label for a BVAR variable."""
    return DISPLAY_LABELS.get(varname, varname)


