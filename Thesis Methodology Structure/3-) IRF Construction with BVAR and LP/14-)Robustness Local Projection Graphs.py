# SECTION 6 — FIGURE LP-1: PRE-2008 FOUR-SHOCK COMPARISON
# ============================================================

def make_figure_pre(out_png: str):
    """
    Produce Figure LP-1: pre-2008 four-shock LP comparison.

    Reads LP coefficient CSVs for AD and FFR (Hybrid) over the pre-2008
    period. Plots median LP coefficients with ±1 HAC standard error bands
    for both series in a two-column panel grid.
    Legend is placed in panel A (upper left panel) only.

    The Hybrid CSV is read and labelled "FFR" — consistent with all other
    thesis figures.

    Parameters
    ----------
    out_png : str  Output PNG file path.
    """
    # Load pre-2008 LP CSV tables (AD and FFR only)
    df_ad  = read_lp_csv(find_csv(LP_DIR, r"lp_AD_PRE\.csv"))
    df_ffr = read_lp_csv(find_csv(LP_DIR, r"lp_HYBRID_PRE\.csv"))

    # Hybrid CSV displayed as "FFR"
    data = {
        "AD":  df_ad,
        "FFR": df_ffr,
    }

    # Retain only variables present in all four CSVs, in VAR_ORDER
    available = [v for v in VAR_ORDER
                 if all(f"{v}_b" in df.columns for df in data.values())]

    n     = len(available)
    ncols = 2
    nrows = int(np.ceil(n / ncols))

    fig, axes = plt.subplots(
        nrows, ncols,
        figsize=(6.5 * ncols, 3.2 * nrows),
        sharex=True,
        constrained_layout=True,
    )
    axes = np.array(axes).reshape(-1)

    panel_letters = "ABCDEF"

    for i, var in enumerate(available):
        ax     = axes[i]
        show_x = (i >= n - ncols)   # show x-axis label on bottom row only

        for label, df in data.items():
            h, b, lo, hi = get_arrays(df, var)
            st = STYLES_PRE[label]
            ax.plot(h, b, label=label,
                    color=st["color"], ls=st["ls"],
                    lw=st["lw"], zorder=st["zorder"])
            ax.fill_between(h, lo, hi,
                            color=st["color"],
                            alpha=FILL_ALPHA_PRE,
                            zorder=st["zorder"] - 1)

        format_ax(ax, PANEL_LABELS.get(var, var), show_xlabel=show_x)
        add_panel_label(ax, panel_letters[i])

        # Legend in panel A only to avoid repetition
        if i == 0:
            ax.legend(
                fontsize=8, framealpha=0.9,
                edgecolor="#cccccc", loc="upper right",
                handlelength=2.2, labelspacing=0.3,
            )

    # Turn off unused panels
    for k in range(n, len(axes)):
        axes[k].axis("off")

    fig.suptitle(
        "Pre-2008 Local Projection Impulse Responses\n"
        "AD and FFR Monetary Policy Shocks  "
        r"$\pm$1 S.E. bands  |  Newey-West HAC",
        fontsize=10, y=1.01, ha="center",
    )

    fig.savefig(out_png, dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"Saved Figure LP-1 → {out_png}")


