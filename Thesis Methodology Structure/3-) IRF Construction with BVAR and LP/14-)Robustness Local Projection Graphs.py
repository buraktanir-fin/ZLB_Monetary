def read_lp_csv(path: str) -> pd.DataFrame:
    """
    Read an LP coefficient CSV produced by lp_results.py.

    Raises FileNotFoundError with the full path if the file is missing,
    allowing the user to immediately identify which LP run is needed.

    Parameters
    ----------
    path : str  Absolute path to the LP CSV file.

    Returns
    -------
    pd.DataFrame  CSV contents with columns h, {var}_b, {var}_lo, {var}_hi.
    """
    if not os.path.exists(path):
        raise FileNotFoundError(f"LP CSV not found:\n  {path}")
    return pd.read_csv(path)


def get_arrays(df: pd.DataFrame, var: str):
    """
    Extract horizon and IRF arrays for one variable from an LP CSV.

    Applies the ×100 scaling factor for log variables so that plotted
    values match the thesis unit convention (100 × log).

    Parameters
    ----------
    df  : pd.DataFrame  LP coefficient CSV loaded by read_lp_csv().
    var : str           Variable name (e.g. 'y1', 'log_rgdp').

    Returns
    -------
    h  : np.ndarray  Horizon array.
    b  : np.ndarray  OLS coefficient (possibly scaled by 100).
    lo : np.ndarray  Lower band (b − 1 HAC SE, possibly scaled).
    hi : np.ndarray  Upper band (b + 1 HAC SE, possibly scaled).
    """
    h  = df["h"].to_numpy()
    sc = 100.0 if var in SCALE_BY_100 else 1.0
    b  = sc * df[f"{var}_b"].to_numpy()
    lo = sc * df[f"{var}_lo"].to_numpy()
    hi = sc * df[f"{var}_hi"].to_numpy()
    return h, b, lo, hi


def find_csv(directory: str, pattern: str) -> str:
    """
    Find the first file in directory whose name fully matches a regex pattern.

    Case-insensitive matching allows the function to handle minor
    capitalisation differences in filenames.

    Parameters
    ----------
    directory : str  Folder to search.
    pattern   : str  Full-match regex pattern for the filename.

    Returns
    -------
    str  Absolute path to the matched file.

    Raises
    ------
    FileNotFoundError  If no matching file is found.
    """
    rx = re.compile(pattern, re.IGNORECASE)
    for fn in sorted(os.listdir(directory)):
        if rx.fullmatch(fn):
            return os.path.join(directory, fn)
    raise FileNotFoundError(
        f"No file matching '{pattern}' in:\n  {directory}"
    )


def add_panel_label(ax, letter, x=-0.12, y=1.05):
    """
    Add a bold alphabetic panel label (A, B, C, ...) to a subplot axis.

    Placed in the upper-left corner outside the plot area, following
    the convention used in academic journal figures.

    Parameters
    ----------
    ax     : matplotlib Axes  Target subplot.
    letter : str              Single uppercase letter label.
    x, y   : float            Position in axes coordinates.
    """
    ax.text(x, y, letter, transform=ax.transAxes,
            fontsize=10, fontweight="bold",
            va="top", ha="left", fontfamily="serif")


def format_ax(ax, ylabel, show_xlabel=False):
    """
    Apply consistent formatting to a single IRF panel.

    Sets a light horizontal zero line, y-axis label, tick formatting,
    and optional x-axis label. Removes the top and right spines via
    rcParams (already set at module level).

    Parameters
    ----------
    ax          : matplotlib Axes  Target subplot.
    ylabel      : str              Y-axis label from PANEL_LABELS.
    show_xlabel : bool             Whether to add 'Months after shock' label.
    """
    ax.axhline(0, color="#999999", lw=0.8, ls="-", zorder=0)
    ax.set_ylabel(ylabel, fontsize=8.5, labelpad=4)
    ax.yaxis.set_major_formatter(ticker.FormatStrFormatter("%.4g"))
    ax.tick_params(axis="both", labelsize=8)
    ax.grid(axis="y", alpha=0.25, lw=0.6)
    if show_xlabel:
        ax.set_xlabel("Months after shock", fontsize=8.5)


