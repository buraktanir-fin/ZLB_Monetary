# SECTION 3 — FILE HELPER FUNCTIONS
# ============================================================

def find_first(pattern: str) -> str:
    """
    Find the first file in IRF_DIR whose name fully matches a regex pattern.

    Regex matching makes the script robust to changes in the p (lag order)
    and H (horizon) values baked into the CSV filenames. The first
    alphabetically sorted match is returned.

    Parameters
    ----------
    pattern : str  Full-match regex pattern for the filename.

    Returns
    -------
    str  Absolute path to the matched file.

    Raises
    ------
    FileNotFoundError  If no matching file is found in IRF_DIR.
    """
    rx = re.compile(pattern)
    for fn in sorted(os.listdir(IRF_DIR)):
        if rx.fullmatch(fn):
            return os.path.join(IRF_DIR, fn)
    raise FileNotFoundError(
        f"Could not find a file matching:\n  {pattern}\nIn:\n  {IRF_DIR}"
    )


def read_irf_csv(path: str):
    """
    Read a saved IRF CSV table and return arrays ready for plotting.

    The CSV format has columns:
        h           — horizon index (0, 1, ..., H)
        {var}_med   — posterior median IRF
        {var}_lo    — lower credible band (16th percentile)
        {var}_hi    — upper credible band (84th percentile)

    Variables are returned in PREFERRED_ORDER where available, with any
    additional variables appended at the end.

    Parameters
    ----------
    path : str  Absolute path to the IRF CSV file.

    Returns
    -------
    h            : np.ndarray   Horizon array (H+1,).
    ordered_vars : list of str  Variable names in PREFERRED_ORDER.
    med          : dict         {var: np.ndarray} posterior medians.
    lo           : dict         {var: np.ndarray} lower credible bands.
    hi           : dict         {var: np.ndarray} upper credible bands.

    Raises
    ------
    ValueError  If 'h' or any required _med/_lo/_hi column is missing.
    """
    df = pd.read_csv(path)

    if "h" not in df.columns:
        raise ValueError(f"'h' column missing in {path}. Columns: {list(df.columns)}")

    h = df["h"].to_numpy()

    # Identify variables from columns ending with _med
    vars_found = []
    for c in df.columns:
        if c.endswith("_med"):
            vars_found.append(c[:-4])

    vars_found   = sorted(set(vars_found))
    ordered_vars = [v for v in PREFERRED_ORDER if v in vars_found] + \
                   [v for v in vars_found if v not in PREFERRED_ORDER]

    med, lo, hi = {}, {}, {}
    for v in ordered_vars:
        med_col = f"{v}_med"
        lo_col  = f"{v}_lo"
        hi_col  = f"{v}_hi"

        if med_col not in df.columns or lo_col not in df.columns or hi_col not in df.columns:
            raise ValueError(
                f"Missing one of {med_col}, {lo_col}, {hi_col} in {path}"
            )

        med[v] = df[med_col].to_numpy()
        lo[v]  = df[lo_col].to_numpy()
        hi[v]  = df[hi_col].to_numpy()

    return h, ordered_vars, med, lo, hi


