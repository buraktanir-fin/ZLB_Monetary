import os
import re
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt


# ============================================================
# SECTION 1 — PATH CONFIGURATION
# ============================================================
# IRF CSV tables are read from irf_outputs_EBP_final/ (produced by
# bvar_irf_estimation.py). Both figures are saved to the same
# thesis_figures_from_csv/ subfolder as the preliminary figures.

BASE_DIR = os.getcwd()
IRF_DIR  = os.path.join(BASE_DIR, "irf_outputs_EBP_final")
OUTDIR   = os.path.join(IRF_DIR, "thesis_figures_from_csv")
os.makedirs(OUTDIR, exist_ok=True)


# ============================================================
# SECTION 2 — DISPLAY SETTINGS
# ============================================================
# DISPLAY_LABELS and PREFERRED_ORDER match thesis_irf_figures.py exactly
# so that variable labels and panel positions are consistent across all
# thesis figures.

DISPLAY_LABELS = {
    "y1":        "1Y Gov Bond (%)",
    "log_sp500": "S&P500 (100 × log)",
    "log_rgdp":  "Real GDP (100 × log)",
    "unemp":     "Unemployment (%)",
    "log_pgdp":  "GDP Deflator (100 × log)",
    "EBP":       "EBP (%)",
}

# Fixed variable order — matches macro_vars in bvar_irf_estimation.py
PREFERRED_ORDER = ["y1", "log_sp500", "log_rgdp", "unemp", "log_pgdp", "EBP"]


def pretty_ylabel(varname: str) -> str:
    """Return the thesis-standard y-axis label for a BVAR variable."""
    return DISPLAY_LABELS.get(varname, varname)


