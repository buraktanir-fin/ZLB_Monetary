# SECTION 5 — MAIN EXECUTION
# ============================================================

def main():
    """
    Main execution function: produce both robustness figures.

    Execution order:
        1.  Locate six IRF CSV files by regex pattern
        2.  Read all six CSVs into horizon arrays and IRF dictionaries
        3.  Compute common variable sets using PREFERRED_ORDER
        4.  Validate horizon consistency across files
        5.  Produce Figure 1: Pre-2008 four-shock comparison
        6.  Produce Figure 2: Post-2008 Wu-Xia vs Krippner
        7.  Print input and output file summary

    The Hybrid CSV is read and passed as "FFR" in Figure 1 because the
    Hybrid series is the FFR-based shock — "Hybrid" is an internal label.
    """

    # ── Step 1: Locate all required IRF CSV files ─────────────────────────────
    # Regex patterns match regardless of exact p and H values in filename
    ad_pre_path  = find_first(r"Table_IRF_AruobaDrechsel_Pre2008_p\d+_H\d+_EBP\.csv")
    ffr_pre_path = find_first(r"Table_IRF_Hybrid_Pre2008_p\d+_H\d+_EBP\.csv")   # displayed as FFR
    wx_pre_path  = find_first(r"Table_IRF_WuXia_Pre2008_p\d+_H\d+_EBP\.csv")
    wx_post_path = find_first(r"Table_IRF_WuXia_Post2008_p\d+_H\d+_EBP\.csv")
    kr_post_path = find_first(r"Table_IRF_Krippner_Post2008_p\d+_H\d+_EBP\.csv")

    # ── Step 2: Read all six CSVs ─────────────────────────────────────────────
    h_ad,  vars_ad,  med_ad,  lo_ad,  hi_ad  = read_irf_csv(ad_pre_path)
    h_ffr, vars_ffr, med_ffr, lo_ffr, hi_ffr = read_irf_csv(ffr_pre_path)
    h_wx,  vars_wx,  med_wx,  lo_wx,  hi_wx  = read_irf_csv(wx_pre_path)

    h_wx_post, vars_wx_post, med_wx_post, lo_wx_post, hi_wx_post = read_irf_csv(wx_post_path)
    h_kr_post, vars_kr_post, med_kr_post, lo_kr_post, hi_kr_post = read_irf_csv(kr_post_path)

    # ── Step 3: Common variable sets in PREFERRED_ORDER ───────────────────────
    # Pre-2008: variables present in all four series
    common_vars_pre = [
        v for v in PREFERRED_ORDER
        if (v in vars_ad and v in vars_ffr and v in vars_wx)
    ]
    if not common_vars_pre:
        common_vars_pre = sorted(
            set(vars_ad).intersection(vars_ffr).intersection(vars_wx)
        )
    if not common_vars_pre:
        raise ValueError("No common variables found across AD, FFR, and Wu-Xia CSVs.")

    # Post-2008: variables present in both series
    common_vars_post = [
        v for v in PREFERRED_ORDER
        if v in vars_wx_post and v in vars_kr_post
    ]
    if not common_vars_post:
        common_vars_post = sorted(set(vars_wx_post).intersection(vars_kr_post))
    if not common_vars_post:
        raise ValueError("No common variables found across Wu-Xia and Krippner post-2008 CSVs.")

    # ── Step 4: Horizon consistency checks ────────────────────────────────────
    if not (len(h_ad) == len(h_ffr) == len(h_wx)):
        raise ValueError("IRF horizons differ across the three pre-2008 CSV files.")
    if not (np.allclose(h_ad, h_ffr) and np.allclose(h_ad, h_wx)):
        raise ValueError("IRF horizon values differ across the three pre-2008 CSV files.")

    if len(h_wx_post) != len(h_kr_post):
        raise ValueError("IRF horizons differ between Wu-Xia and Krippner post-2008 CSVs.")
    if not np.allclose(h_wx_post, h_kr_post):
        raise ValueError("IRF horizon values differ between Wu-Xia and Krippner post-2008 CSVs.")

    h_pre  = h_ad
    h_post = h_wx_post

    # ── Figure 1: Pre-2008 four-shock comparison ──────────────────────────────
    out_png_pre = os.path.join(
        OUTDIR,
        "Figure_Pre2008_Compare_AD_FFR_WuXia.png"
    )

    plot_four_shock_pre_comparison(
        h         = h_pre,
        vars_list = common_vars_pre,
        irf_dict  = {
            "AD":       (med_ad,  lo_ad,  hi_ad),
            "FFR":      (med_ffr, lo_ffr, hi_ffr),
            "Wu-Xia":   (med_wx,  lo_wx,  hi_wx),
        },
        title   = "Pre-2008: Comparison of IRFs to AD, FFR, and Wu-Xia Monetary Policy Shocks",
        out_png = out_png_pre,
    )

    # ── Figure 2: Post-2008 Wu-Xia vs Krippner ───────────────────────────────
    out_png_post = os.path.join(
        OUTDIR,
        "Figure_Post2008_Compare_WuXia_Krippner.png"
    )

    plot_two_shock_post_comparison(
        h         = h_post,
        vars_list = common_vars_post,
        irf_dict  = {
            "Wu-Xia":   (med_wx_post, lo_wx_post, hi_wx_post),
            "Krippner": (med_kr_post, lo_kr_post, hi_kr_post),
        },
        title   = (
            "Post-2008: Comparison of IRFs to Wu-Xia and Krippner "
            "Shadow Rate Monetary Policy Shocks\n"
            "ZLB Period | Median IRFs with 68% credible intervals"
        ),
        out_png = out_png_post,
    )

    # ── Summary ───────────────────────────────────────────────────────────────
    print("\nDone.")
    print("Inputs (pre-2008):")
    print("  AD       :", ad_pre_path)
    print("  FFR      :", ffr_pre_path, " (Hybrid CSV displayed as FFR)")
    print("  Wu-Xia   :", wx_pre_path)
    print("Inputs (post-2008):")
    print("  Wu-Xia   :", wx_post_path)
    print("  Krippner :", kr_post_path)
    print("Outputs:")
    print(" ", out_png_pre)
    print(" ", out_png_post)


if __name__ == "__main__":
    main()