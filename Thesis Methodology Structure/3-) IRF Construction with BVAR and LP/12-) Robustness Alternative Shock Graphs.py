def plot_four_shock_pre_comparison(h, vars_list, irf_dict, title, out_png):
    """
    Plot median IRFs from four pre-2008 shock series in the same panels.

    Displays median lines only (no credible bands) to keep the four-series
    comparison visually uncluttered. Each series receives a distinct line
    style for identification in black-and-white reproduction.

    Used for Figure 1 (Section 6.1): pre-2008 four-shock comparison.

    Parameters
    ----------
    h         : np.ndarray   Horizon array.
    vars_list : list of str  Variables to plot (in PREFERRED_ORDER).
    irf_dict  : dict         {label: (med, lo, hi)} for each shock series.
                             Keys must be: "AD", "FFR", "Wu-Xia".
    title     : str          Figure suptitle.
    out_png   : str          Output PNG file path.
    """
    n     = len(vars_list)
    nrows = int(np.ceil(n / 2))
    fig, axes = plt.subplots(nrows, 2, figsize=(12, 4 * nrows), sharex=True)
    axes = np.array(axes).reshape(-1)

    # Distinct line styles — distinguishable in greyscale
    line_styles = {
        "AD":       "-",
        "FFR":      "--",
        "Wu-Xia":   ":",
    }

    SCALE_BY_100 = ["log_sp500", "log_rgdp", "log_pgdp"]

    for i, v in enumerate(vars_list):
        ax = axes[i]
        sc = 100.0 if v in SCALE_BY_100 else 1.0

        for label, (med, _, _) in irf_dict.items():
            ax.plot(
                h,
                sc * med[v],
                linewidth=2,
                linestyle=line_styles.get(label, "-"),
                label=label
            )

        ax.axhline(0, linewidth=1)
        ax.set_ylabel(pretty_ylabel(v))
        ax.grid(True)
        ax.legend()

    for k in range(n, len(axes)):
        axes[k].axis("off")

    fig.suptitle(title, y=1.02, fontsize=14)
    plt.tight_layout()
    plt.savefig(out_png, dpi=300, bbox_inches="tight")
    plt.show()
    print(f"Saved: {out_png}")


def plot_two_shock_post_comparison(h, vars_list, irf_dict, title, out_png):
    """
    Plot two post-2008 shadow rate IRF sets with 68% credible bands.

    Displays posterior median lines with 68% credible bands (15% opacity)
    for both Wu-Xia and Krippner series. Each series has a distinct colour
    and line style.

    Used for Figure 2 (Section 6.2): post-2008 Wu-Xia vs Krippner.

    Parameters
    ----------
    h         : np.ndarray   Horizon array.
    vars_list : list of str  Variables to plot (in PREFERRED_ORDER).
    irf_dict  : dict         {label: (med, lo, hi)} for each shock series.
                             Keys must be: "Wu-Xia", "Krippner".
    title     : str          Figure suptitle.
    out_png   : str          Output PNG file path.
    """
    # Colour and line style scheme — distinguishable in greyscale
    styles = {
        "Wu-Xia":   dict(color="#2ca02c", ls=":",  lw=2.2),
        "Krippner": dict(color="#d62728", ls="-.", lw=2.2),
    }

    n     = len(vars_list)
    nrows = int(np.ceil(n / 2))
    fig, axes = plt.subplots(nrows, 2,
                             figsize=(12, 4 * nrows),
                             sharex=True)
    axes = np.array(axes).reshape(-1)

    SCALE_BY_100 = ["log_sp500", "log_rgdp", "log_pgdp"]

    for i, v in enumerate(vars_list):
        ax = axes[i]
        sc = 100.0 if v in SCALE_BY_100 else 1.0

        for label, (med, lo, hi) in irf_dict.items():
            st = styles[label]
            ax.plot(h, sc * med[v], label=label,
                    color=st["color"], ls=st["ls"], lw=st["lw"])
            ax.fill_between(h, sc * lo[v], sc * hi[v],
                            color=st["color"], alpha=0.15)

        ax.axhline(0, color="steelblue", linewidth=0.9)
        ax.set_ylabel(pretty_ylabel(v))
        ax.set_title(v, fontsize=9)
        ax.grid(True, alpha=0.3)
        ax.legend(fontsize=8, loc="best")

    for k in range(n, len(axes)):
        axes[k].axis("off")

    fig.suptitle(title, y=1.02, fontsize=13)
    plt.tight_layout()
    plt.savefig(out_png, dpi=300, bbox_inches="tight")
    plt.show()
    print(f"Saved: {out_png}")


